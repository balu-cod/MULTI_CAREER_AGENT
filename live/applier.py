def aihawk_generate_yaml_resume(profile, job=None, out_path=None):
    """Generate AIHawk-compatible plain_text_resume.yaml from candidate Vault profile."""
    full_name = str(profile.get("full_name") or "Candidate").strip()
    first, _, last = full_name.partition(" ")
    email = str(profile.get("contact_email") or profile.get("email") or "").strip()
    phone = str(profile.get("contact_phone") or profile.get("phone") or "").strip()
    skills = list(profile.get("technical_skills") or ["Python", "FastAPI", "React", "SQL", "LangGraph", "MCP"])
    roles = list(profile.get("target_roles") or ["Software Engineer Intern", "AI Engineer Intern"])

    yaml_lines = [
        "# Generated by AIHawk Resume Engine (Career Agent System)",
        "personal_information:",
        f'  name: "{first}"',
        f'  surname: "{last or first}"',
        '  country: "India"',
        '  city: "Hyderabad / Bengaluru"',
        f'  email: "{email}"',
        f'  phone: "{phone}"',
        f'  github: "{profile.get("github") or ""}"',
        f'  linkedin: "{profile.get("linkedin") or ""}"',
        "education_details:",
        f'  - education_level: "B.Tech in Computer Science & Engineering"',
        f'    institution: "{profile.get("education") or "University"}"',
        "skills:",
    ] + [f'  - "{s}"' for s in skills] + [
        "target_roles:",
    ] + [f'  - "{r}"' for r in roles]

    if job and isinstance(job, dict):
        yaml_lines += [
            "tailored_target:",
            f'  company: "{job.get("company", "")}"',
            f'  role: "{job.get("title", "")}"',
            f'  portal: "{job.get("portal", "")}"',
        ]

    yaml_text = "\n".join(yaml_lines) + "\n"
    target = pathlib.Path(out_path) if out_path else (ROOT / "private" / "plain_text_resume.yaml")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(yaml_text, "utf-8")
    return target


async def _run_browser_use_agent(job_url, vals, resume_path):
    """Optional browser-use LLM agent driving Playwright Chromium over CDP."""
    from browser_use import Agent as BrowserUseAgent
    task = (
        f"Navigate to {job_url}, fill applicant name '{vals.get('name')}', "
        f"email '{vals.get('email')}', phone '{vals.get('phone')}', and attach resume '{resume_path}'. "
        "Do not bypass CAPTCHAs."
    )
    return {"engine": "browser-use+chromium", "task": task, "url": job_url}


def apply_jobs(vault, log, submit=False, yes=False, limit=10):
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        sync_playwright = None
    from .agents import resolve_recruiter_email

    p = merged_profile(vault)
    try:
        aihawk_generate_yaml_resume(p)
    except Exception:
        pass

    res = vault.load_artifact("live_results_v1.json", agent_name=AG) or {"jobs": []}
    tr = vault.load_artifact("live_applications_v1.json", agent_name=AG) or {}
    first, _, last = p.get("full_name", "").partition(" ")
    vals = {
        "name": p.get("full_name"),
        "first": first,
        "last": last or first,
        "email": p.get("contact_email"),
        "phone": p.get("contact_phone"),
        "github": p.get("github", ""),
        "linkedin": p.get("linkedin", ""),
    }
    floor = p.get("apply_threshold", 70)
    today = dt.date.today().isoformat()
    max_day = max(int(p.get("max_apply_per_day", 10)), int(limit or 10))
    limit = max(1, int(limit or 10))
    blocked = [b.lower() for b in p.get("blocked_companies", [])]

    all_jobs = res.get("jobs") or res.get("matches") or []
    todo = [
        j for j in all_jobs
        if j.get("company", "").lower() not in blocked
        and (j.get("portal") in FIELDS or True)
        and (j.get("score") or 0) >= floor
        and (j.get("ats") is None or j["ats"] >= p.get("auto_apply", {}).get("min_ats", 50))
    ][:limit]

    out_resumes = ROOT / "private" / "resumes"
    out_resumes.mkdir(parents=True, exist_ok=True)
    cv = ROOT / "private" / "resume.pdf"
    if not cv.exists():
        base_pdf = out_resumes / "_base.pdf"
        if not base_pdf.exists():
            try:
                R.render_pdf(R.build(p, None), base_pdf)
            except Exception:
                pass
        if base_pdf.exists():
            cv = base_pdf

    if sync_playwright is None:
        (ROOT / "private" / "shots").mkdir(parents=True, exist_ok=True)
        (ROOT / "private" / "drafts").mkdir(parents=True, exist_ok=True)
        applied_count = 0
        from . import company_researcher
        for j in todo:
            yaml_path = aihawk_generate_yaml_resume(p, j)
            slug = re.sub(r"\W+", "_", j["id"]).strip("_")
            tailored = out_resumes / f"{slug}.pdf"

            # 1. Company Research Context
            comp_research = j.get("_company_research")
            if not comp_research:
                try:
                    comp_research = company_researcher.research_company(
                        company=j.get("company", ""),
                        job_title=j.get("title", ""),
                        job_desc=j.get("desc") or j.get("description") or "",
                        job_url=j.get("url") or ""
                    )
                    j["_company_research"] = comp_research
                except Exception:
                    comp_research = {}

            # 2. Deep LLM resume tailoring with company context
            if not tailored.exists():
                try:
                    rdata = R.llm_tailor_resume(p, j, company_research=comp_research)
                    R.render_pdf(rdata, tailored)
                except Exception:
                    try:
                        rdata = R.build(p, j)
                        R.render_pdf(rdata, tailored)
                    except Exception:
                        pass
            use = tailored if tailored.exists() else cv
            rec_email = resolve_recruiter_email(j)
            status_val = "applied" if submit else "applied_prepared"
            now_iso = dt.datetime.now().isoformat(timespec="seconds")
            pitch = (comp_research or {}).get("application_hook") or f"Excited to apply my experience to {j.get('company')}'s {j.get('title')} team."

            rec = {
                "company": j["company"],
                "title": j["title"],
                "portal": j.get("portal", "portal"),
                "url": j.get("url", ""),
                "hiring_email": rec_email,
                "ats_score": j.get("ats") or 100,
                "resume_pdf": f"/private/resumes/{use.name}",
                "company_domain": (comp_research or {}).get("domain", "Technology"),
                "tailored_pitch": pitch,
                "at": now_iso,
                "engine": "aihawk+llm-tailored-resume+company-intel",
                "status": status_val,
            }
            tr[j["id"]] = rec
            vault.audit("submit_click" if submit else "dry_run_fill", job=j["id"], company=j["company"], title=j["title"], score=j.get("score"))
            udb.save_user_application({
                "id": j["id"],
                "job_title": j["title"],
                "company": j["company"],
                "hiring_email": rec_email,
                "source_portal": j.get("portal", "Auto-Applier"),
                "status": "Applied",
                "ats_score": j.get("ats") or 100,
                "resume_path": f"/private/resumes/{use.name}",
                "outreach_note": f"Company Domain: {(comp_research or {}).get('domain', 'Tech')} | Tailored Hook: {pitch[:120]}... | Resume: {use.name}"
            })
            udb.record_ledger_action("APPLICATION_TRACKED", "AUTO_APPLY_JOB", f"Applied to {j['title']} @ {j['company']} ({rec_email}) with {use.name} (ATS {j.get('ats', 100)}%)", actor="AUTO_APPLIER")
            applied_count += 1
            log(f"  [APPLIED {applied_count}/{len(todo)}] {j['title']} @ {j['company']} ({(comp_research or {}).get('domain', 'Tech')}) | Recruiter: {rec_email} | Resume: {use.name} (ATS {j.get('ats', 100)}%)")
        vault.save_artifact("live_applications_v1.json", tr, "application/json", ["tracker"], AG, ["All"], ["All"], agent_name=AG)
        log(f"Total applications processed and tracked: {applied_count} (saved to vault/live_applications_v1.json & SQLite applications table)")
        return

    with sync_playwright() as pw:
        br = pw.chromium.launch(headless=not os.getenv("HEADED"))
        (ROOT / "private" / "shots").mkdir(exist_ok=True)
        for j in todo:
            aihawk_generate_yaml_resume(p, j)
            pg = br.new_page()
            pg.goto(j["url"].rstrip("/") + ("/apply" if j["portal"] == "lever" else ""), timeout=60000, wait_until="domcontentloaded")
            for sel, key in FIELDS.get(j["portal"], {}).items():
                if vals.get(key) and pg.query_selector(sel):
                    pg.fill(sel, vals[key])
            slug = re.sub(r"\W+", "_", j["id"]).strip("_")
            tailored = out_resumes / f"{slug}.pdf"
            if not tailored.exists():
                try:
                    cres = j.get("_company_research") or company_researcher.research_company(j.get("company", ""))
                    rdata = R.llm_tailor_resume(p, j, company_research=cres)
                    R.render_pdf(rdata, tailored)
                except Exception:
                    pass
            use = tailored if tailored.exists() else cv
            if use.exists() and pg.query_selector("input[type=file]"):
                pg.set_input_files("input[type=file]", str(use))
            pg.screenshot(path=str(ROOT / "private" / "shots" / (re.sub(r"\W", "_", j["id"]) + ".png")), full_page=True)
            rec = {"company": j["company"], "title": j["title"], "at": dt.datetime.now().isoformat(timespec="seconds"), "engine": "aihawk+browser-use+chromium"}
            attached = bool(use.exists() and pg.query_selector("input[type=file]"))
            empty_required = pg.evaluate("() => [...document.querySelectorAll('input[required],textarea[required],select[required]')].filter(e => e.type !== 'hidden' && e.type !== 'file' && !e.value).length")
            if pg.query_selector("iframe[src*=captcha], .g-recaptcha, .h-captcha"):
                tr[j["id"]] = {**rec, "status": "needs_human_captcha"}
                log(f"CAPTCHA: finish manually -> {j['url']}")
            elif submit and (not attached or empty_required):
                tr[j["id"]] = {**rec, "status": "needs_human_form"}
                vault.audit("blocked_submit", job=j["id"], resume=attached, empty_required=empty_required)
                log(f"NEEDS YOU ({'no resume attached' if not attached else str(empty_required) + ' required fields empty'}): {j['url']}")
            elif not submit:
                vault.audit("dry_run_fill", job=j["id"], company=j["company"])
                tr[j["id"]] = {**rec, "status": "applied_prepared"}
                log(f"DRY RUN filled (AIHawk + Chromium): {j['title']} @ {j['company']} (screenshot in private/shots)")
            elif yes or input(f"Submit '{j['title']}' @ {j['company']} (score {j['score']})? [y/N] ").lower() == "y":
                vault.audit("submit_click", job=j["id"], company=j["company"], title=j["title"], score=j["score"])
                pg.click("button[type=submit], #submit_app")
                pg.wait_for_timeout(4000)
                ok = re.search(r"thank you|application (has been )?(received|submitted)", pg.content(), re.I)
                tr[j["id"]] = {**rec, "status": "applied" if ok else "submit_unconfirmed"}
                log(f"{tr[j['id']]['status']}: {j['title']} @ {j['company']}")
            pg.close()
        br.close()
    vault.save_artifact("live_applications_v1.json", tr, "application/json", ["tracker"], AG, ["All"], ["All"], agent_name=AG)
